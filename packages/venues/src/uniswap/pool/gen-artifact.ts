// writes artifact.ts from forge's output. run after `forge build` in this folder:
//   cd packages/venues/src/uniswap/pool && forge build && bun run gen-artifact.ts
import { join } from "node:path";

const dir = import.meta.dir;
const out = await Bun.file(join(dir, "out/TestPool.sol/TestPool.json")).json();
const body = `// generated by gen-artifact.ts from src/TestPool.sol (solc 0.8.24, optimizer 200 runs). do not edit
export const testPoolAbi = ${JSON.stringify(out.abi, null, 2)} as const;

export const testPoolBytecode = "${out.bytecode.object}" as const;
`;
await Bun.write(join(dir, "artifact.ts"), body);
console.log(`wrote artifact.ts: ${out.abi.length} abi entries, ${(out.bytecode.object.length - 2) / 2} bytes of init code`);
